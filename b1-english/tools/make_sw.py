# Regenerates sw.js: core files are cached on install, pictures and audio are cached in the background after activation.
import hashlib, os, json
os.chdir(os.path.join(os.path.dirname(__file__), '..'))
core = ['./', 'index.html', 'manifest.webmanifest', 'icon-512.png', 'apple-touch-icon.png',
        'data/words.json', 'data/grammar.json', 'data/patterns.json']
core = [c for c in core if c == './' or os.path.exists(c)]
assets = []
for d in ['img', 'audio/w', 'audio/e', 'audio/p']:
    if os.path.isdir(d):
        assets += sorted(f'{d}/{f}' for f in os.listdir(d))
h = hashlib.sha1()
for f in core[1:] + assets:
    h.update(f.encode()); h.update(str(os.path.getsize(f)).encode())
V = 'b1e-' + h.hexdigest()[:10]
js = f'''// Offline support for B1 English (generated by tools/make_sw.py)
const V="{V}";
const CORE={json.dumps(core)};
const ASSETS={json.dumps(assets)};
async function fill(){{const c=await caches.open(V);for(let i=0;i<ASSETS.length;i+=30){{const part=ASSETS.slice(i,i+30);const have=await Promise.all(part.map(u=>c.match(u)));await Promise.all(part.filter((u,k)=>!have[k]).map(u=>c.add(u).catch(()=>{{}})));}}}}
self.addEventListener("install",e=>{{e.waitUntil(caches.open(V).then(c=>c.addAll(CORE)).then(()=>self.skipWaiting()));}});
self.addEventListener("activate",e=>{{e.waitUntil((async()=>{{for(const k of await caches.keys())if(k!==V)await caches.delete(k);await self.clients.claim();fill();}})());}});
self.addEventListener("fetch",e=>{{const r=e.request;if(r.method!=="GET")return;const u=new URL(r.url);if(u.origin!==location.origin)return;
  if(r.mode==="navigate"){{e.respondWith(caches.match("index.html").then(m=>m||fetch(r)));return;}}
  e.respondWith(caches.match(r,{{ignoreSearch:true}}).then(m=>m||fetch(r).then(res=>{{if(res.ok){{const cp=res.clone();caches.open(V).then(c=>c.put(r,cp));}}return res;}})));}});
'''
open('sw.js', 'w').write(js)
print(V, len(core), 'core,', len(assets), 'assets')
